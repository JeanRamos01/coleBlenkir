-- Esquema PostgreSQL · Colegio Blenkir
-- Es idempotente: se ejecuta en cada arranque sin borrar datos.

CREATE TABLE IF NOT EXISTS docentes (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombres      VARCHAR(120) NOT NULL,
    especialidad VARCHAR(120) NOT NULL,
    email        VARCHAR(150) NOT NULL UNIQUE,
    estado       VARCHAR(10)  NOT NULL DEFAULT 'activo' CHECK (estado IN ('activo','inactivo'))
);

CREATE TABLE IF NOT EXISTS estudiantes (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombres   VARCHAR(100) NOT NULL,
    apellidos VARCHAR(100) NOT NULL,
    dni       VARCHAR(15)  NOT NULL UNIQUE CHECK (dni ~ '^[0-9]{6,15}$'),
    grado     VARCHAR(30)  NOT NULL,
    seccion   VARCHAR(1)   NOT NULL CHECK (seccion IN ('A','B','C')),
    estado    VARCHAR(10)  NOT NULL DEFAULT 'activo' CHECK (estado IN ('activo','inactivo'))
);

-- Un docente con cursos NO se puede borrar (RESTRICT), igual que en la web
CREATE TABLE IF NOT EXISTS cursos (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre     VARCHAR(120) NOT NULL,
    id_docente BIGINT NOT NULL REFERENCES docentes(id) ON DELETE RESTRICT,
    creditos   INT NOT NULL CHECK (creditos BETWEEN 1 AND 10)
);

-- Matrícula de estudiantes en cursos (antes: state.asignaciones)
CREATE TABLE IF NOT EXISTS asignaciones (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_curso      BIGINT NOT NULL REFERENCES cursos(id)      ON DELETE CASCADE,
    id_estudiante BIGINT NOT NULL REFERENCES estudiantes(id) ON DELETE CASCADE,
    UNIQUE (id_curso, id_estudiante)
);

CREATE TABLE IF NOT EXISTS notas (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_curso      BIGINT NOT NULL REFERENCES cursos(id)      ON DELETE CASCADE,
    id_estudiante BIGINT NOT NULL REFERENCES estudiantes(id) ON DELETE CASCADE,
    bimestre      INT NOT NULL CHECK (bimestre BETWEEN 1 AND 4),
    calificacion  NUMERIC(4,1) NOT NULL CHECK (calificacion BETWEEN 0 AND 20),
    fecha         DATE NOT NULL DEFAULT CURRENT_DATE
);

CREATE TABLE IF NOT EXISTS asistencias (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_curso      BIGINT NOT NULL REFERENCES cursos(id)      ON DELETE CASCADE,
    id_estudiante BIGINT NOT NULL REFERENCES estudiantes(id) ON DELETE CASCADE,
    fecha         DATE NOT NULL,
    estado        VARCHAR(12) NOT NULL CHECK (estado IN ('Presente','Tardanza','Inasistencia')),
    UNIQUE (id_curso, id_estudiante, fecha)
);

-- Reemplaza el arreglo USUARIOS_DEMO del front. La contraseña se guarda con BCrypt.
CREATE TABLE IF NOT EXISTS usuarios (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario       VARCHAR(50)  NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    tipo          VARCHAR(15)  NOT NULL CHECK (tipo IN ('Administrador','Docente','Alumno','APODERADO')),
    nombre        VARCHAR(120) NOT NULL,
    id_estudiante BIGINT REFERENCES estudiantes(id) ON DELETE CASCADE,
    id_docente BIGINT REFERENCES docentes(id) ON DELETE CASCADE
);

-- Migración idempotente para instalaciones existentes
ALTER TABLE usuarios ADD COLUMN IF NOT EXISTS id_docente BIGINT REFERENCES docentes(id) ON DELETE CASCADE;

-- Amplía de forma segura el catálogo de roles en bases que ya tenían el esquema anterior.
ALTER TABLE usuarios DROP CONSTRAINT IF EXISTS usuarios_tipo_check;
ALTER TABLE usuarios DROP CONSTRAINT IF EXISTS ck_usuarios_tipo_rol;
ALTER TABLE usuarios ADD CONSTRAINT ck_usuarios_tipo_rol
    CHECK (tipo IN ('Administrador','Docente','Alumno','APODERADO'));

-- Perfil del apoderado: una cuenta de usuario tiene un único perfil de apoderado.
CREATE TABLE IF NOT EXISTS apoderados (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL UNIQUE REFERENCES usuarios(id) ON DELETE CASCADE
);

-- Vinculación autorizada entre apoderados y estudiantes, con permisos granulares.
CREATE TABLE IF NOT EXISTS apoderado_estudiante (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    apoderado_id         BIGINT NOT NULL REFERENCES apoderados(id) ON DELETE CASCADE,
    estudiante_id        BIGINT NOT NULL REFERENCES estudiantes(id) ON DELETE CASCADE,
    parentesco           VARCHAR(40) NOT NULL DEFAULT 'Apoderado',
    puede_ver_notas      BOOLEAN NOT NULL DEFAULT TRUE,
    puede_ver_asistencia BOOLEAN NOT NULL DEFAULT TRUE,
    puede_ver_alertas    BOOLEAN NOT NULL DEFAULT TRUE,
    activo               BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_apoderado_estudiante UNIQUE (apoderado_id, estudiante_id)
);
CREATE INDEX IF NOT EXISTS idx_apoderado_estudiante_apoderado ON apoderado_estudiante(apoderado_id);
CREATE INDEX IF NOT EXISTS idx_apoderado_estudiante_estudiante ON apoderado_estudiante(estudiante_id);

CREATE INDEX IF NOT EXISTS idx_cursos_docente      ON cursos(id_docente);
CREATE INDEX IF NOT EXISTS idx_asig_estudiante     ON asignaciones(id_estudiante);
CREATE INDEX IF NOT EXISTS idx_notas_estudiante    ON notas(id_estudiante);
CREATE INDEX IF NOT EXISTS idx_notas_curso         ON notas(id_curso);
CREATE INDEX IF NOT EXISTS idx_asist_estudiante    ON asistencias(id_estudiante);
CREATE UNIQUE INDEX IF NOT EXISTS uq_usuario_estudiante ON usuarios(id_estudiante) WHERE id_estudiante IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_usuario_docente ON usuarios(id_docente) WHERE id_docente IS NOT NULL;
